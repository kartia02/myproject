def all_time_expressions():
    return [e for group in TIME_EXPRESSIONS.values() for e in group]


def time_expressions(*kinds):
    """종류를 골라 시간 표현을 모은다. 예) time_expressions("time_of_day", "clock")"""
    return [e for k in kinds for e in TIME_EXPRESSIONS[k]]
